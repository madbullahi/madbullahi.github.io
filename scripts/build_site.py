#!/usr/bin/env python3
"""Build the GitHub Pages copy (index.html) from the live Claude-hosted site.

Usage:
    python3 -I scripts/build_site.py <saved-live-page.html> index.html

The live page (https://claude.ai/artifact/4TKo2VvsTrtr93AnAwqn49) is the source
of truth. This script copies its content (the site-data JSON), styles, markup
template and display script into a normal standalone web page, and removes the
parts that only work on Claude: the "Post an update" tools and the republish
code. Attachments on project-log posts link back to the Claude-hosted site.
"""
import json
import re
import sys

LIVE_URL = "https://claude.ai/artifact/4TKo2VvsTrtr93AnAwqn49"
DESC = ("Muhammad Abdullahi, PhD — Alexander von Humboldt Research Fellow, "
        "Goethe University Frankfurt. Ecotoxicology, bioremediation and "
        "Daphnia-based water treatment.")


def grab(pattern, text, what):
    m = re.search(pattern, text, re.S)
    if not m:
        sys.exit(f"build_site: could not find {what} in the live page")
    return m.group(1)


def main(src_path, out_path):
    live = open(src_path, encoding="utf-8").read()
    data = json.loads(grab(r'<script type="application/json" id="site-data">\s*(.*?)\s*</script>', live, "site-data JSON"))
    style = grab(r'<style id="page-style">(.*?)</style>', live, "page style")
    tpl = grab(r'<template id="tpl">(.*?)</template>', live, "page template")
    app = grab(r'<script id="app">(.*?)</script>', live, "page script")

    # Drop Claude-only code: republish machinery and owner tools.
    app = re.sub(r"  /\* ---------- canonical source.*?(?=  /\* ---------- state \+ helpers)", "", app, flags=re.S)
    app = re.sub(r"  /\* ---------- owner tools.*?(?=  /\* ---------- hero)", "", app, flags=re.S)
    app = app.replace('href="/_blob/${file.id}"', f'href="{LIVE_URL}#humboldt"')
    for banned in ("artifact.publish", "claude.use"):
        if banned in app:
            sys.exit(f"build_site: Claude-only code ({banned}) still present; the page script changed shape")

    # Drop owner-only markup.
    tpl = re.sub(r'\s*<div id="composer-slot"></div>', "", tpl)
    tpl = re.sub(r'\s*<div class="owner-bar".*?</div>', "", tpl, flags=re.S)

    json_txt = json.dumps(data, ensure_ascii=False, indent=1).replace("<", "\\u003c")
    icon = ("data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 32 32'%3E"
            "%3Ccircle cx='16' cy='16' r='15' fill='%231C6B66'/%3E%3Ctext x='16' y='21' "
            "font-family='Georgia,serif' font-size='14' fill='white' text-anchor='middle'%3EMA%3C/text%3E%3C/svg%3E")
    html = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>Muhammad Abdullahi</title>
<meta name="description" content="{DESC}">
<meta property="og:title" content="Muhammad Abdullahi, PhD">
<meta property="og:description" content="{DESC}">
<meta property="og:type" content="profile">
<meta property="og:url" content="https://madbullahi.github.io/">
<meta property="og:image" content="https://madbullahi.github.io/og.png">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:image" content="https://madbullahi.github.io/og.png">
<link rel="canonical" href="https://madbullahi.github.io/">
<link rel="icon" href="{icon}">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Spectral:ital,wght@0,300;0,500;1,300&family=IBM+Plex+Sans:wght@400;500;600&family=IBM+Plex+Mono:wght@400;500&display=swap">
<style>
:root {{ padding-top: env(safe-area-inset-top, 0px); padding-bottom: env(safe-area-inset-bottom, 0px); }}
body {{ margin: 0; }}
img {{ max-width: 100%; }}
{style}
</style>
</head>
<body>
<!-- Generated by scripts/build_site.py from {LIVE_URL}. Do not edit by hand: changes are overwritten at the next sync. -->
<template id="tpl">{tpl}</template>
<div id="root"></div>
<noscript><p style="padding:24px;font-family:sans-serif">Muhammad Abdullahi, PhD. Alexander von Humboldt Research Fellow, Goethe University Frankfurt. Please enable JavaScript to view this site.</p></noscript>
<script type="application/json" id="site-data">
{json_txt}
</script>
<script>{app}</script>
</body>
</html>
"""
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(html)
    print(f"build_site: wrote {out_path} ({len(html)} bytes, {len(data.get('publications', []))} publications, "
          f"{len(data.get('log', []))} log posts, updated {data.get('updated')})")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
